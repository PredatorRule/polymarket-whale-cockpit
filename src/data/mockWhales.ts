import type { WhaleTrader, WhalePosition, WhaleCategory, Outcome } from "../types/whale";

let posSeq = 0;
function pos(
  marketTitle: string,
  outcome: Outcome,
  shares: number,
  avgPrice: number,
  currentPrice: number,
  category: WhaleCategory,
  timestamp: string,
  isLocked: boolean,
): WhalePosition {
  const totalCost = shares * avgPrice;
  const pnl = shares * (currentPrice - avgPrice);
  const pnlPercent = avgPrice > 0 ? ((currentPrice - avgPrice) / avgPrice) * 100 : 0;
  posSeq += 1;
  return {
    id: `pos-${posSeq}`,
    marketTitle,
    outcome,
    shares,
    avgPrice,
    currentPrice,
    pnl,
    pnlPercent,
    totalCost,
    category,
    timestamp,
    isLocked,
  };
}

